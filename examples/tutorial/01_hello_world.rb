# The most basic Ruby program - printing text to the screen
puts "Hello, World!"

# puts stands for "put string" - it prints text and adds a new line
puts "Welcome to Ruby programming!"

# You can also use print (no automatic new line)
print "This is on one line... "
print "and this continues on the same line.\n"

# \n is a special character that creates a new line

# You can print numbers too
puts 42
puts 3.14

# Try changing the text in quotes and run this program!
puts "Change this text to whatever you want!"

