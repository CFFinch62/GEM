# Numbers and math operations
a = 10
b = 3

puts "Addition: #{a + b}"
puts "Subtraction: #{a - b}"
puts "Multiplication: #{a * b}"
puts "Division: #{a / b}"  # Integer division
puts "Float division: #{a.to_f / b}"
puts "Modulus (remainder): #{a % b}"
puts "Exponent: #{a ** b}"

# Shorthand assignment
x = 5
x += 2  # Same as x = x + 2
puts "x after += 2: #{x}"